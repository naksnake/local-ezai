"""Renderer — Registry v2 + runtime descriptors → rendered artifacts
(PR-3, ADR-026 R-1/R-3/R-4; docs/MODEL_ROUTING_DESIGN.md §6,
docs/PROVIDER_ABSTRACTION.md §3, docs/RUNTIME_ABSTRACTION_STRATEGY.md §4).

    registry.yaml  ─┐
                    ├─ render() ─► litellm-config.yaml      (models + role-* aliases → engine)
    providers/*.yaml┘             docker-compose.engine.yml (engine-slot materialization)
    capability vector             role_map.yaml             (ADR-020 shape for agentd)
                                  capability_report.yaml    (negotiation evidence)
                                  [engine-models.ini]       (multi-model preset)
                                  manifest.yaml             (hashes → drift detection)

Rules realized here:

- **Roles are the interface.** LiteLLM serves ``role-<role>`` aliases next
  to model aliases; both point at the engine slot through its neutral
  network alias ``engine`` (never the historical service name).
- **Capability negotiation at render time** (CF-6): for every role, every
  model in its resolution chain must satisfy the role contract on its
  runtime — tool calling (parser ∈ runtime parsers), JSON output, context
  — and be in a format the runtime serves. Failures are loud and name the
  missing capability; nothing fails silently at request time.
- **One engine slot, one runtime.** The active set must be servable by the
  selected runtime; conflicts are explained in plain language.
- **Rendered files are outputs.** Every artifact carries a GENERATED banner
  and a hash in the manifest; ``write_rendered`` refuses to overwrite a
  hand-edited artifact (drift) unless forced.
- **No runtime or hardware knowledge in this module.** Images, flags,
  parsers, devices come from descriptor data; this module fills templates.

Until the PR-7 cutover the renderer writes to a parallel path
(``<config>/rendered/``); the hand-written LiteLLM configs stay in place.
"""

